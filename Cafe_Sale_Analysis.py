import pandas as pd
import numpy as np 
df=pd.read_csv(r'C:\Users\HP\Desktop\A-22\Project_case_sale\dirty_cafe_sales.csv')
print(df)

#Step1 Inspection and standardizing
print(df.head())
print(df.info()) 
print(df.isna().sum())
print(df.describe())
# standardizing the column name
df.columns=(
    df.columns
    .str.strip()
    .str.lower()
    .str.replace(" ","_")
)
print(df.columns)
#standardizing the values in these three object column
text_cols=['item','payment_method','location']
for col in text_cols:
    df[col]=df[col].str.lower().str.strip()
#checking the count of each value before replacing missing values
print("before replacing missing values ")
print(df["item"].value_counts())
print(df["payment_method"].value_counts())
print(df["location"].value_counts())

#Step 2 Handling the fake missing value
fake_missing=["ERROR","UNKNOWN","unknown","N/A","NA",""," ","error"]
df.replace(fake_missing,np.nan,inplace=True)

#checking the count of each value after replacing missing values
print('after replacing missing values')
print(df["item"].value_counts())
print(df["payment_method"].value_counts())
print(df["location"].value_counts())

#converting the present datatype into required one
df["quantity"]=pd.to_numeric(
    df["quantity"],errors="coerce"
)
df["transaction_date"]=pd.to_datetime(
    df["transaction_date"],errors="coerce"
)
df["total_spent"]=pd.to_numeric(
    df["total_spent"],errors="coerce"
)
df["price_per_unit"]=pd.to_numeric(
    df["price_per_unit"],errors="coerce"
)

print(df.head())
print(df.info())
print(df.isna().sum())

#removing the 
# df=df.dropna(subset=['item'])
# print(df.head(30))
#Imputing the null values with something meaningful
df["quantity"]=df["quantity"].fillna(df["quantity"].median())
df["price_per_unit"]=df["price_per_unit"].fillna(df["price_per_unit"].median())
df["payment_method"]=df["payment_method"].fillna("not_specified")
df['location']=df["location"].fillna("unknown")

# creating a new column revenue to generate insight 
df["revenue"]=df["quantity"]*df["price_per_unit"]
print(df.isna().sum())
#1. to find top selling items , which created the highest revenue top 5 items by
print("Top 5 selling items which created the highest revenue")
print(df.groupby(["item"])["revenue"].sum().sort_values(ascending=False).head())
# 2. location wise which created the highest revenue
print("location wise which created the highest revenue")
print(df.groupby(["location"])["revenue"].sum().sort_values(ascending=False))

print("monthly revenue, by how much % it is increasing or decreasing")
print("Monthly revenue are: ")
df["month"]=df["transaction_date"].dt.month
df["monthly_revenue"]=df.groupby(["month"])["revenue"].sum()
print((df.groupby(["month"])["revenue"].sum()/df["revenue"].sum())*100)
print((df.groupby(["month"])["revenue"].sum()/df["revenue"].sum()).pct_change()*100)

print("Product was sold least so we can apply some marketing strategies")
print(df.groupby(["item"])["quantity"].count().sort_values(ascending=True))

print("revenue generated by each item")
print(df.groupby(["item"])["revenue"].sum().sort_values(ascending=False))

print("Percentage{%} revenue generated by each item")
print(((df.groupby(["item"])["revenue"].sum()/df["revenue"].sum())*100).sort_values(ascending=False))

print("Percentage{%} revenue generated by each item in each month")
print(((df.groupby(["item","month"])["revenue"].sum()/df["revenue"].sum())*100).sort_values(ascending=False))

print("Percentage{%} change revenue generated by each item in each month")
# print((((df.groupby(["item","month"])["revenue"].sum()/df["revenue"].sum())*100).sort_values(ascending=False)).pct_change*100)
item_pct = (
    df.groupby(["item", "month"])["revenue"].sum()
    / df["revenue"].sum()
    * 100
)
item_pct = item_pct.reset_index(name="pct_revenue")
item_pct = item_pct.sort_values(["item", "month"])
item_pct["pct_change"] = (
    item_pct.groupby("item")["pct_revenue"]
            .pct_change() * 100
)
growth_summary = (
    item_pct.groupby("item")["pct_change"]
            .mean()
            .sort_values(ascending=False)
)

print(growth_summary)
